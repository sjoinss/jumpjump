export type PixelIconName = keyof typeof ICONS;

/** 행마다 이어진 칸을 하나의 rect로 합친다 */
function toRects(rows: readonly string[]) {
  const rects: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const on = row[x] === "#";
      if (on && start < 0) start = x;
      if (!on && start >= 0) {
        rects.push({ x: start, y, w: x - start });
        start = -1;
      }
    }
  });
  return rects;
}

const CACHE = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => [name, { w: rows[0].length, h: rows.length, rects: toRects(rows) }]),
) as Record<PixelIconName, { w: number; h: number; rects: ReturnType<typeof toRects> }>;

export function PixelIcon({ name, size = 20, className }: { name: PixelIconName; size?: number; className?: string }) {
  const icon = CACHE[name];
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox={`0 0 ${icon.w} ${icon.h}`}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {icon.rects.map((r) => (
        <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </svg>
  );
}
